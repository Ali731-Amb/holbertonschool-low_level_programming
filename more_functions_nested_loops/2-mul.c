/**
 * mul - multiplie deux entiers.
 * @a: premier nombre
 * @b: deuxième nombre
 *
 * Return: le résultat de la multiplication de a et b
 */

int mul(int a, int b)
{
    // On calcule le résultat de la multiplication des deux entiers
    int res_multi = a * b;

    // On retourne le résultat
    return (res_multi);
}
